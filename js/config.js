// Адрес серверной части: единственное место, где клиент знает, где стоит
// бот. Обычно вопросы идут туда же, откуда приехала страница, — сам бот
// её и раздаёт. Прямой адрес нужен зеркалам и GitHub Pages: там сервера
// рядом нет.
//
// Пустая строка выключает всё серверное: приложение работает как раньше,
// просто без учёта заходов и без админки.
//
// ДОМ — адрес, по которому сервер бота живёт всегда. Он же запасной путь
// для страниц, раздатчик которых сервером не оказался (зеркало, чужая
// статика), и он же адрес для Pages.
//
// ЭТО ЕДИНСТВЕННОЕ МЕСТО В КЛИЕНТЕ, КОТОРОЕ ЗНАЕТ, ГДЕ СТОИТ БОТ. При
// переезде на другой хостинг меняется одна эта строка — см. раздел
// «Переезд на Railway» в DEPLOY.md. Пропустить её значит получить
// работающее приложение, которое при первой же осечке уходит на
// выключённый сервер и там остаётся.
const HOME = 'https://miet-bot-rouk.amvera.io';

// Запасной вход — воркер Cloudflare (mirror/worker.js), проксирующий к
// тому же серверу. Нужен не «на всякий случай»: 25.09.2026 у владельца на
// мобильном интернете открывался только он, а на Wi-Fi — только HOME.
// Поэтому клиент знает обе дороги и сам переходит на ту, что работает.
export const MIRROR = 'https://miet-mirror.rokdoker09.workers.dev';

// Зеркало на GitHub Pages — единственное место, откуда страница
// раздаётся, а сервера рядом нет: там спрашивать надо Amvera.
const PAGES_HOST = 'rouk69.github.io';

// Откуда открыли — тому и задаём вопросы. Иначе запасной вход не имеет
// смысла: страница приехала бы через него, а данные всё равно ушли бы
// прямиком на Amvera — то есть по тому самому пути, который у человека
// и оборвался. Свой origin безопасен: страницу раздал тот, кого нам
// назначил бот, чужим он стать не может.
function here() {
  try {
    if (location.protocol !== 'https:' && location.protocol !== 'http:') return '';
    if (location.hostname === PAGES_HOST) return '';
    return location.origin || '';
  } catch {
    return '';
  }
}

const DEFAULT_BASE = here() || HOME;

// Локальная отладка: в консоли браузера
//   localStorage.setItem('miet-api', 'http://localhost:8080')
// Через параметр адреса (?api=…) переопределять НЕЛЬЗЯ намеренно: по
// присланной ссылке подписанная initData уехала бы на чужой сервер, а с ней
// и возможность действовать от имени человека.
function stored() {
  try {
    return localStorage.getItem('miet-api') || '';
  } catch {
    return '';
  }
}

// Дороги к серверу по порядку: откуда пришла страница, прямая, зеркало.
const ROUTES = [...new Set([DEFAULT_BASE, HOME, MIRROR].filter(Boolean))];

// Какая дорога сработала в этой сети — помним полчаса: сеть у человека
// меняется (Wi-Fi → мобильный), и вечная память завела бы не туда.
const ROUTE_KEY = 'miet-route';
const ROUTE_TTL = 30 * 60 * 1000;

function rememberedRoute() {
  try {
    const r = JSON.parse(localStorage.getItem(ROUTE_KEY) || 'null');
    if (r && ROUTES.includes(r.base) && Date.now() - r.at < ROUTE_TTL) return r.base;
  } catch { /* нет памяти — начнём с первой дороги */ }
  return '';
}

/** Запомнить дорогу, которая сейчас ответила. */
export function rememberRoute(b = base) {
  try { localStorage.setItem(ROUTE_KEY, JSON.stringify({ base: b, at: Date.now() })); } catch { /* ну и ладно */ }
}

let base = (stored() || rememberedRoute() || DEFAULT_BASE).replace(/\/+$/, '');

/** Адрес серверной части прямо сейчас. */
export const apiBase = () => base;

/**
 * Возврат на прямой путь, если тот, кто раздал страницу, сервером не
 * оказался.
 *
 * Такое бывает: приложение выложили ещё куда-нибудь статикой, человек
 * открыл его оттуда — и остался без расписания, потому что спрашивать
 * данные он стал у раздатчика, а там API нет. Прямой адрес известен
 * всегда, так что лучше молча уйти на него, чем показать пустой экран.
 *
 * Возвращает false, если уходить некуда — мы уже там.
 */
export function fallBackToHome() {
  if (base === HOME) return false;
  base = HOME;
  return true;
}

/**
 * Следующая дорога, которую этот запрос ещё не пробовал. Возвращает false,
 * если пробовать больше нечего. При ручной настройке (`miet-api`) дорогу
 * не меняем: отладка должна идти туда, куда сказали.
 */
export function switchRoute(tried) {
  if (stored()) return false;
  const next = ROUTES.find(r => !tried.has(r));
  if (!next) return false;
  base = next;
  return true;
}

// Совместимость: адрес, с которого начали. Для новых мест — apiBase().
export const API_BASE = base;

